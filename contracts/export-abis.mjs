// Writes the ABIs the apps need into packages/shared/src/abis.generated.ts. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";

const names = [
  "OddraBook",
  "OddraMatchRegistry",
  "OddraTreasury",
  "OddraRiskManager",
  "OddraFeeCollector",
  "OddraTestUSDG",
];
let out = "// Generated by contracts/export-abis.mjs. Do not edit.\n\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(new URL(`./out/${n}.sol/${n}.json`, import.meta.url), "utf8"));
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync(new URL("../packages/shared/src/abis.generated.ts", import.meta.url), out);
console.log("wrote", names.length, "ABIs");
